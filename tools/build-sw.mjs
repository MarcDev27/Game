// Regenerates sw.js with a precache list of every game file and a content-hash cache version.
// Run after changing files: node tools/build-sw.mjs
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const files = ['index.html', 'styles.css', 'manifest.webmanifest'];
const walk = (dir) => {
  for (const f of fs.readdirSync(path.join(root, dir))) {
    const rel = path.posix.join(dir, f);
    if (fs.statSync(path.join(root, rel)).isDirectory()) walk(rel);
    else if (/\.(js|png)$/.test(f)) files.push(rel);
  }
};
walk('src'); walk('icons');
const hash = crypto.createHash('sha1');
for (const f of files.sort()) hash.update(fs.readFileSync(path.join(root, f)));
const version = hash.digest('hex').slice(0, 10);

const sw = `// Generated by tools/build-sw.mjs. Offline cache for the Neon Strata PWA.
const CACHE = 'neon-strata-${version}';
const FILES = ${JSON.stringify(['./', ...files], null, 2)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});

self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).then((res) => {
    const copy = res.clone();
    caches.open(CACHE).then((c) => c.put(e.request, copy));
    return res;
  })));
});
`;
fs.writeFileSync(path.join(root, 'sw.js'), sw);
console.log('sw.js written:', files.length, 'files, cache', version);
